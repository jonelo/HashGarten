    // Read properties
    private void readProperties() {
        props = new Properties();
        File file = new File(AppConstants.PROPERTIES_FILE);
        if (!file.exists()) {
            // the normal case on the very first run, nothing worth reporting
            return;
        }
        try ( InputStream input = new FileInputStream(file)) {
            props.load(input);
        } catch (IOException io) {
            debug(String.format("Could not read %s: %s", AppConstants.PROPERTIES_FILE, io.getMessage()));
        }
    }

    // Save some properties
    private void saveProperties() {
        try ( OutputStream output = new FileOutputStream(AppConstants.PROPERTIES_FILE)) {
            props.store(output, null);
        } catch (IOException io) {
            debug(String.format("Could not write %s: %s", AppConstants.PROPERTIES_FILE, io.getMessage()));
        }
    }

    // Overrule the command line args by the properties stored by the app
    // from an earlier run  
    private void initParameters() {

        // Parameters from Props
        Parameters parametersFromProps = null;
        if (props.getProperty(PropertyKeys.JACKSUM_PARAMETERS_BASE64) != null) {
            try {
                parametersFromProps = (Parameters) IO.base64StringToObject(props.getProperty(PropertyKeys.JACKSUM_PARAMETERS_BASE64));

                // if we have saved the location to a check file, we need to set
                // it to null, because we want to control verification mode at the GUI by command line args
                // (at the file browser integration)
                parametersFromProps.setCheckFile(null);
                // make sure that the filenames to be checked are removed from a previous run
                parametersFromProps.setFilenamesFromCheckFile(null);
                // a file list is usually a temporary file that has been created by the file browser
                // integration for a previous run, and it is gone by now; if a file list is required,
                // the file browser integration passes a fresh one by command line args
                parametersFromProps.setFilelistFilename(null);
                // older versions have saved the secret key as well; drop it, so that it also
                // disappears from the properties file when the settings are saved the next time
                if (isSecretKey(parametersFromProps.getKey())) {
                    parametersFromProps.setKey((Sequence) null);
                }
                parametersFromProps.getVerbose().setDefault();

                // parametersFromProps.setParameterModifiedByAPI(true);
/*
   debug("parameters from props:\n" + String.join(" ", parametersFromProps.getCLIParametersWithQuotes()));
   debug("algorithm:\n" + parametersFromProps.getAlgorithm());
   debug("algorithmIdentifier:\n" + parametersFromProps.getAlgorithmIdentifier());
                 */
            } catch (IOException | ClassNotFoundException ex) {
                debug("The remembered parameters could not be read: " + ex);
            }
        } else {
            parametersFromProps = null;
        }

        // Parameters from CLI
        Parameters parametersFromCLI = null;
        try {
            parametersFromCLI = new CLIParameters(args).parse().unchecked();
            // parsed CLIParameters return a parameters object with -h enabled
            // by default, we don't need that here
            parametersFromCLI.setHelp(false);

            // parametersFromCLI.setParameterModifiedByAPI(true);
/*
   debug("parameters from CLI:\n" + String.join(" ", parametersFromCLI.getCLIParametersWithQuotes()));
   debug("algorithm:\n" + parametersFromCLI.getAlgorithm());
   debug("algorithmIdentifier:\n" + parametersFromCLI.getAlgorithmIdentifier());
             */
        } catch (ParameterException ex) {
            // e.g. an unknown option; start with the remembered resp. default settings instead of
            // failing with a NullPointerException below
            debug(ex.toString());
            JOptionPane.showMessageDialog(null, String.format(
                    "The command line arguments are invalid, they are ignored:%n%s", ex.getMessage()),
                    "HashGarten", JOptionPane.WARNING_MESSAGE);
            parametersFromCLI = new Parameters();
            parametersFromCLI.setHelp(false);
        }

        // set the parameter object member depenent to the availability of
        // parameters in the properties file and from the command line
        if (parametersFromProps != null) {
            // Parameters.update() always takes over the header setting, even if the command line
            // has neither --header nor --no-header, so the remembered setting would always be lost
            boolean headerWanted = parametersFromProps.isHeaderWanted();
            boolean headerWantedExplicitlySet = parametersFromProps.isHeaderWantedExplicitlySet();
            parametersFromProps.update(parametersFromCLI);
            if (!parametersFromCLI.isHeaderWantedExplicitlySet()) {
                parametersFromProps.setHeaderWanted(headerWanted);
                parametersFromProps.setHeaderWantedExplicitlySet(headerWantedExplicitlySet);
            }
            parameters = parametersFromProps;
        } else {
            parameters = parametersFromCLI;
        }

        // A style with a hardcoded algorithm (e.g. names-only, which uses "none") replaces the
        // algorithm during the check. The GUI would then show "none", and after switching back
        // to the default style a task would run with "none", which prints the file sizes instead
        // of hash values. So keep the algorithm the user has selected; a task with such a style
        // still uses the style's algorithm, because the style is applied again for every task.
        String algorithmSelected = parameters.getAlgorithm();

        // "-c relative" (file browser integration) stands for a check file next to the first file,
        // see buildRelativeFilename(). Jacksum checks that a check file exists before it resolves
        // --path-relative-to-entry, so the check would abort before the directory is known. Hence
        // the check file is left out of the check and resolved to a real filename afterwards.
        boolean checkFileRelative = "relative".equals(parameters.getCheckFile());
        if (checkFileRelative) {
            parameters.setCheckFile(null);
        }
        try {
            checkParameters(false);
            if (parameters.getCompatibilityID() != null && algorithmSelected != null) {
                parameters.setAlgorithm(algorithmSelected);
            }
            // adjust the object again, no stdin for the GUI
            parameters.setStdinForFilenamesFromArgs(false);

            // parameters.expandFileList();
            // parameters.restoreStdErr();
            // parameters.restoreStdOut();
        } catch (ParameterException | ExitException ex) {
            debug("The parameters are invalid: " + ex);
        }
        if (checkFileRelative) {
            String directory = parameters.getPathRelativeTo() != null
                    ? parameters.getPathRelativeTo().toString()
                    : "";
            // the same algorithm that parameters2calculationPanel() shows, so the name matches the
            // one that a calculation with "-O relative" has written
            String algorithm = parameters.isAlgorithmSetByUser()
                    ? parameters.getAlgorithm()
                    : parameters.getAlgorithmIdentifier();
            parameters.setCheckFile(buildRelativeFilename(directory, algorithm));
        }
        // parameters.setParameterModifiedByAPI(true);
/*
   debug("parameters checked:\n" + String.join(" ", parameters.getCLIParametersWithQuotes()));
   debug("algorithm:\n" + parameters.getAlgorithm());
   debug("algorithmIdentifier:\n" + parameters.getAlgorithmIdentifier());
         */
    }

    /**
     * Validates the parameter object, and repairs the path options if they are the reason why the
     * validation failed.
     *
     * HashGarten keeps one long living parameter object and calls checked() on it again and again
     * (at startup, on every keystroke in the Interactive operating mode, and when the action
     * button is pressed). Up to and including Jacksum 4.0.0 that is not always possible:
     * checked() derives --path-relative-to from --path-relative-to-entry without clearing the
     * entry, so every subsequent call is rejected with "Only one of the following options is
     * allowed: ...".
     * A path that has been remembered from a previous run can also have gone away in the meantime
     * (e.g. an unmounted volume), which lets checked() fail as well.
     *
     * Therefore the failing call is retried once with normalized path options. Newer Jacksum
     * versions that keep checked() repeatable are not affected by the workaround, they keep the
     * path options that the user resp. the file browser integration has specified.
     *
     * @param setupStreams whether the output and error streams should be set up, see Jacksum's
     *                     Parameters.checked(boolean)
     * @throws ParameterException if the parameters are invalid for a different reason
     * @throws ExitException if Jacksum requests an exit
     */
    private void checkParameters(boolean setupStreams) throws ParameterException, ExitException {
        try {
            parameters = parameters.checked(setupStreams);
        } catch (ParameterException pe) {
            if (!normalizePathOptions()) {
                throw pe;
            }
            debug("Retrying to check the parameters with normalized path options, because of: " + pe.getMessage());
            parameters = parameters.checked(setupStreams);
        }
    }

    /**
     * Makes sure that at most one of the mutually exclusive path options
     * (--no-path, --path-absolute, --path-relative-to, --path-relative-to-entry) is set,
     * and that a path that is set actually exists.
     *
     * @return true if the parameter object has been changed
     */
    private boolean normalizePathOptions() {
        if (parameters == null) {
            return false;
        }
        boolean changed = false;
        String pathRelativeTo = parameters.getPathRelativeToAsString();
        if (pathRelativeTo != null) {
            boolean exists;
            try {
                exists = Files.exists(Paths.get(pathRelativeTo));
            } catch (InvalidPathException ipe) {
                exists = false;
            }
            if (!exists) {
                // the path is gone (e.g. an unmounted volume), don't insist on it
                parameters.setPathRelativeToAsString(null);
                parameters.setPathRelativeTo(null);
                changed = true;
            }
        }
        if (parameters.getPathRelativeToEntry() > 0 && parameters.getPathRelativeToAsString() != null) {
            // the entry has already been resolved to a concrete path, so keep the path only
            parameters.setPathRelativeToEntry(0);
            changed = true;
        }
        return changed;
    }

    // Read values from the parameters object and update the properties object
    private void updatePropertiesFromParameters() {
        // pathRelativeTo is a java.nio.file.Path, which is not serializable; Parameters.checked()
        // derives it from pathRelativeToAsString, so it is left out and put back afterwards
        java.nio.file.Path pathRelativeTo = parameters.getPathRelativeTo();
        parameters.setPathRelativeTo(null);
        // the properties file is plain text, so a secret key must not be saved, see isSecretKey()
        Sequence key = parameters.getKey();
        if (isSecretKey(key)) {
            parameters.setKey((Sequence) null);
        }
        try {
            props.setProperty(PropertyKeys.JACKSUM_PARAMETERS_BASE64, IO.objectToBase64String(parameters));
        } catch (IOException ex) {
            debug("The parameters could not be saved: " + ex);
        } finally {
            parameters.setPathRelativeTo(pathRelativeTo);
            parameters.setKey(key);
        }
    }

    /**
     * Tells whether a key is the secret itself (text, password or hex), which must not be
     * remembered across runs. A key file is not: the key is just the name of the file then, and
     * remembering that is as harmless as remembering any other filename.
     *
     * @param key the key, may be null
     * @return true if the key must not be saved
     */
    private static boolean isSecretKey(Sequence key) {
        return key != null && key.getType() != Sequence.Type.FILE;
    }

