    // the tooltips the components carry while there is no error, so that they can be restored
    private final Map<javax.swing.JComponent, String> toolTipBackup = new java.util.HashMap<>();

    /**
     * Flags a component as the cause of a user input error: FlatLaf paints an error outline around
     * it and the reason becomes its tooltip.
     *
     * No color is set explicitly, so the mark follows the current theme - FlatLaf resolves it to
     * Component.error.borderColor, which is defined separately for the light and the dark theme.
     *
     * @param component the component that the user has to correct
     * @param message the reason, may be null
     */
    private void markInputError(javax.swing.JComponent component, String message) {
        toolTipBackup.putIfAbsent(component, component.getToolTipText());
        component.putClientProperty(FlatClientProperties.OUTLINE, FlatClientProperties.OUTLINE_ERROR);
        component.setToolTipText(message == null || message.isEmpty()
                ? "The input is not valid." : message);
    }

    /**
     * Flags a component whose input is valid, but has no effect: FlatLaf paints a warning outline
     * around it and the reason becomes its tooltip. It is removed by clearInputError().
     *
     * No color is set explicitly, so the mark follows the current theme - FlatLaf resolves it to
     * Component.warning.borderColor, which is defined separately for the light and the dark theme.
     *
     * @param component the component that the user should have a look at
     * @param message the reason
     */
    private void markInputWarning(javax.swing.JComponent component, String message) {
        toolTipBackup.putIfAbsent(component, component.getToolTipText());
        component.putClientProperty(FlatClientProperties.OUTLINE, FlatClientProperties.OUTLINE_WARNING);
        component.setToolTipText(message);
    }

    /**
     * Removes the error mark and restores the tooltip that the component had before.
     *
     * @param component the component that is fine again
     */
    private void clearInputError(javax.swing.JComponent component) {
        component.putClientProperty(FlatClientProperties.OUTLINE, null);
        if (toolTipBackup.containsKey(component)) {
            component.setToolTipText(toolTipBackup.get(component));
        }
    }

    /**
     * Builds the key from the key field and the key type, as it is passed to Jacksum.
     *
     * @return the key, or null if there is none
     */
    private Sequence keyFromFields() {
        String key = new String(keyPasswordField.getPassword());
        Object type = keyTypeComboBox.getSelectedItem();
        if (key.isEmpty() && (!isHmacSelected() || "File".equals(type))) {
            // an empty key is no key at all: it would make Parameters.isKey() return true, and
            // Jacksum would then put "-k txt:" into the header of the output file, even if the
            // selected algorithm is not an HMAC at all.
            // An empty file name is not an empty key either, so Jacksum reports the missing key.
            return null;
        } else if (key.isEmpty()) {
            // an HMAC accepts an empty key (RFC 2104 pads it with zeros), so pass an empty key
            // rather than none, otherwise Jacksum rejects the HMAC for lacking a key; this is
            // the same as -k txt: on the command line
            return new Sequence(Sequence.Type.TXT, "");
        } else if ("Text".equals(type) || "Password".equals(type)) {
            return new Sequence("txt:" + key);
        } else if ("File".equals(type)) {
            return new Sequence("file:" + key);
        } else if ("Hex".equals(type)) {
            return new Sequence("hex:" + key);
        }
        return null;
    }

    /**
     * The minimal key length that RFC 2104 recommends for an HMAC algorithm.
     *
     * @param bytes the length in bytes
     * @param algorithm the HMAC algorithm that requires it, as selected
     * @param hash the name of the underlying hash function
     */
    private record KeyMinimum(int bytes, String algorithm, String hash) {
    }

    // "hmac:" or "hmac-", the name of the hash, and an optional output length in bits, the same
    // as Jacksum's HMAC_Selector parses it
    private static final java.util.regex.Pattern HMAC_NAME =
            java.util.regex.Pattern.compile("(?i)hmac[:-](.+?)(:\\d+)?");

    /**
     * The minimal key length that RFC 2104 recommends for the selected HMAC algorithms: "In any
     * case the minimal recommended length for K is L bytes (as the hash output length)". It is
     * computed like Jacksum does for --info (AlgoInfoAction, HMAC.init()).
     *
     * The HMAC is created directly rather than by JacksumAPI.getChecksumInstance(), which would
     * initialize it with the key that Jacksum holds globally, and fail without one.
     *
     * @return the largest minimum of the selected HMAC algorithms, or null if none is selected
     */
    private KeyMinimum recommendedMinimumKeyLength() {
        KeyMinimum max = null;
        for (String algorithm : algoTextField.getText().split("\\+")) {
            java.util.regex.Matcher matcher = HMAC_NAME.matcher(algorithm.trim());
            if (!matcher.matches()) {
                continue;
            }
            try {
                net.jacksum.algorithms.HMAC hmac = new net.jacksum.algorithms.HMAC(
                        matcher.group(1).toLowerCase(java.util.Locale.ROOT));
                int bytes = hmac.getAlgorithm().getSize() / 8;
                if (max == null || bytes > max.bytes()) {
                    max = new KeyMinimum(bytes, algorithm.trim(), hmac.getAlgorithm().getName());
                }
            } catch (java.security.NoSuchAlgorithmException | RuntimeException e) {
                // an unknown algorithm is reported elsewhere
            }
        }
        return max;
    }

    /**
     * Flags the key field with a warning if the key is shorter than RFC 2104 recommends for the
     * selected HMAC algorithms. The callers clear the key field first; an error or another
     * warning that they have set since takes precedence and is left alone.
     *
     * Only lengths are reported, never the key itself, which may be a password.
     */
    private void updateKeyLengthWarning() {
        if (keyPasswordField.getClientProperty(FlatClientProperties.OUTLINE) != null) {
            return;
        }
        String message = keyLengthMessage();
        if (message != null) {
            markInputWarning(keyPasswordField, message);
        }
    }

    /**
     * Checks the key outside the Interactive mode, which checks it along with the input: a key
     * that can't be decoded (e.g. invalid hex) is flagged as an error, a short key with a warning.
     *
     * A key file is not read here, because this runs on every keystroke.
     */
    private void checkKey() {
        clearInputError(keyPasswordField);
        Sequence key = keyFromFields();
        if (key != null && key.getType() != Sequence.Type.FILE) {
            try {
                key.asBytes();
            } catch (RuntimeException e) {
                markInputError(keyPasswordField, e.getMessage());
                return;
            }
        }
        if (key != null && !isHmacSelected()) {
            markInputWarning(keyPasswordField, KEY_WITHOUT_HMAC_WARNING);
            return;
        }
        updateKeyLengthWarning();
    }

    // Jacksum uses the key for HMAC algorithms only and ignores it silently otherwise, so without
    // a hint typing a key would seem to have no effect at all
    private static final String KEY_WITHOUT_HMAC_WARNING = "The key has no effect, because it is "
            + "used by HMAC algorithms only (e.g. hmac:sha-256), and none of the selected algorithms is one.";

    // the reason why the key is too short, or null if it is long enough or can't be checked
    private String keyLengthMessage() {
        KeyMinimum minimum = recommendedMinimumKeyLength();
        if (minimum == null) {
            return null;
        }
        Sequence key = keyFromFields();
        if (key == null) {
            return null;
        }
        long length;
        try {
            if (key.getType() == Sequence.Type.FILE) {
                // don't read the whole file on every keystroke, its size is all we need
                java.nio.file.Path path = java.nio.file.Paths.get(key.getPayload());
                if (!java.nio.file.Files.isRegularFile(path) || !java.nio.file.Files.isReadable(path)) {
                    return null;
                }
                length = java.nio.file.Files.size(path);
            } else {
                length = key.asBytes().length;
            }
        } catch (IOException | RuntimeException e) {
            // e.g. invalid hex; the callers report that as an error themselves
            return null;
        }
        if (length >= minimum.bytes()) {
            return null;
        }
        return String.format("The key has %d %s. RFC 2104 recommends at least %d bytes for %s "
                + "(the output length of %s).", length, length == 1 ? "byte" : "bytes",
                minimum.bytes(), minimum.algorithm(), minimum.hash());
    }

    // true if at least one of the selected algorithms is an HMAC
    private boolean isHmacSelected() {
        return algoTextField.getText().toLowerCase().contains("hmac:");
    }

    /**
     * Sets the tooltip that the key field carries while there is no warning or error, depending
     * on whether an HMAC is selected. Call it whenever the algorithm selection changes.
     *
     * The text is stored as the backup as well, so that clearInputError() restores it rather than
     * an empty tooltip. An active warning or error keeps its tooltip until it is cleared.
     */
    private void updateKeyToolTip() {
        String text = isHmacSelected()
                ? "At least one HMAC algorithm has been selected. This is the key for all selected HMAC algorithms."
                : "The key for HMAC algorithms (e.g. hmac:sha-256). It has no effect unless an HMAC algorithm is selected.";
        toolTipBackup.put(keyPasswordField, text);
        if (keyPasswordField.getClientProperty(FlatClientProperties.OUTLINE) == null) {
            keyPasswordField.setToolTipText(text);
        }
    }

    // all components that the Interactive operating mode can blame for an error
    private void clearInteractiveErrors() {
        clearInputError(interactiveInputTextField);
        clearInputError(keyPasswordField);
        clearInputError(algoTextField);
    }

    /**
     * Reports an invalid interactive input at the component that caused it.
     *
     * The output field is cleared on purpose: it would otherwise keep the hash of an earlier input,
     * which the user could copy without noticing that it does not belong to the current input.
     *
     * @param culprit the component the user has to correct
     * @param message the reason, may be null
     */
    private void interactiveInvalid(javax.swing.JComponent culprit, String message) {
        interactiveOutputTextField.setText("");
        markInputError(culprit, message);
        parameters.setSequence((Sequence) null);
    }

    /**
     * Maps the selection of the input type combo box onto the Sequence type that Jacksum expects.
     *
     * @return the Sequence type
     * @throws IllegalArgumentException if the selected item is not mapped, which is a defect
     */
    private Sequence.Type interactiveInputType() throws IllegalArgumentException {
        String selected = String.valueOf(interactiveInputTypeComboBox.getSelectedItem());
        switch (selected) {
            case "Text": return Sequence.Type.TXT;
            case "Password": return Sequence.Type.TXT;
            case "Formatted Text": return Sequence.Type.TXTF;
            case "Hex": return Sequence.Type.HEX;
            case "Base32": return Sequence.Type.BASE32;
            case "Base32hex": return Sequence.Type.BASE32HEX;
            case "Base64": return Sequence.Type.BASE64;
            case "Base64 for URL": return Sequence.Type.BASE64URL;
            case "Decimal": return Sequence.Type.DEC;
            case "Binary": return Sequence.Type.BIN;
            case "Octal": return Sequence.Type.OCT;
            case "Z85": return Sequence.Type.Z85;
            case "BubbleBabble": return Sequence.Type.BUBBLEBABBLE;
            case "z-base-32": return Sequence.Type.ZBASE32;
            default:
                throw new IllegalArgumentException(String.format("Unsupported input type: %s", selected));
        }
    }

    private void interactiveInputTextFieldKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_interactiveInputTextFieldKeyReleased
        // The component the user would have to correct. It is moved on as we go, so that the error
        // outline ends up on the field that actually caused the problem rather than on the output.
        javax.swing.JComponent culprit = keyPasswordField;
        try {
            clearInteractiveErrors();
            // calculationPanel2parameters() leaves the algorithm alone if the field is empty, so
            // the output would keep showing the hash of the algorithm that was selected before
            if (algoTextField.getText().isEmpty()) {
                culprit = algoTextField;
                throw new IllegalArgumentException("No algorithm has been selected.");
            }
            calculationPanel2parameters();

            // Decode the key on its own. Parameters.checked() decodes it too, so without this a
            // key that cannot be decoded would be blamed on the algorithm field.
            if (parameters.isKey()) {
                parameters.getKey().asBytes();
            }

            culprit = interactiveInputTextField;
            Sequence.Type sequenceType = interactiveInputType();
            Sequence sequence = new Sequence(sequenceType,
                    new String(interactiveInputTextField.getPassword()));
            // Sequence keeps its payload undecoded, and Actions.getChecksumInstance() decodes it
            // later on, so decode it here to have an invalid input blamed on the input field.
            // The bytes are reused below, that also avoids decoding the same input twice.
            byte[] inputBytes = sequence.asBytes();
            parameters.setSequence(sequence);

            culprit = algoTextField;
            checkParameters(false);
            interactiveChecksum = Actions.getChecksumInstance(parameters);

            interactiveChecksum.setFilename("");
            interactiveChecksum.update(inputBytes);

            Encoding enc = (Encoding) interactiveOutputTypeComboBox.getSelectedItem();
            if (enc == null) {
                throw new IllegalArgumentException("No output type has been selected.");
            }
            interactiveOutputTextField.setText(interactiveChecksum.getValueFormatted(enc));
            parameters.setSequence((Sequence) null);

            // Jacksum uses the key for HMAC algorithms only and ignores it silently otherwise, so
            // without a hint typing a key would seem to have no effect at all
            if (parameters.isKey() && !isHmacSelected()) {
                markInputWarning(keyPasswordField, KEY_WITHOUT_HMAC_WARNING);
            }
            updateKeyLengthWarning();

        } catch (ExitException | ParameterException | IllegalArgumentException ex) {
            // An error the user can fix. This method runs on every keystroke, so it must not open a
            // dialog; the outline plus the tooltip report it right at the field instead.
            interactiveInvalid(culprit, ex.getMessage());
        } catch (Exception e) {
            // not a user input error but a defect, so keep the details in the log
            debug(String.format("Interactive mode: %s", e));
            interactiveInvalid(culprit, String.format("Unexpected error, see %s", AppConstants.LOG_FILE));
        }
    }//GEN-LAST:event_interactiveInputTextFieldKeyReleased

