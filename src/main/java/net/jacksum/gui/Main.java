    /**
     * Maps a timestamp format that Jacksum understands onto the corresponding item of the
     * timestamp format combo boxes.
     *
     * The value cannot simply be compared with the items of the combo box: Jacksum knows aliases
     * ("iso" for "iso8601", "iso-utc" for "iso8601utc") and its set of keywords may grow. Treating
     * a keyword as a custom pattern would put it into the pattern text field, and the next run
     * would fail, because Jacksum feeds a custom pattern to SimpleDateFormat.
     *
     * @param timestampFormat the value of Jacksum's --timestamp option
     * @return the item of the combo box, or null if the format is a custom pattern
     */
    private static String timestampKeyword2comboItem(String timestampFormat) {
        if (timestampFormat == null || !TimestampFormatter.isFormatASupportedKeyword(timestampFormat)) {
            // it is a SimpleDateFormat pattern, not a keyword
            return null;
        }
        switch (timestampFormat) {
            case TimestampFormatter.KEY_ISO:
                return TimestampFormatter.KEY_ISO8601;
            case TimestampFormatter.KEY_ISO_UTC:
                return TimestampFormatter.KEY_ISO8601_UTC;
            default:
                return timestampFormat;
        }
    }

    /**
     * Selects a character set in one of the character set combo boxes. They list the canonical
     * names only, while Jacksum also accepts aliases (e.g. "latin1" for "ISO-8859-1"); without
     * resolving them, setSelectedItem() would ignore the alias, and the next task would silently
     * use the character set that happens to be selected (UTF-8 by default).
     */
    private static void selectCharset(JComboBox comboBox, String charsetName) {
        String canonical = charsetName;
        try {
            canonical = java.nio.charset.Charset.forName(charsetName).name();
        } catch (IllegalArgumentException e) {
            // unknown or unsupported, Jacksum reports it when the task is started
        }
        comboBox.setSelectedItem(canonical);
    }

    /**
     * Selects a style in one of the style combo boxes. A style that is not one of its items, e.g.
     * an alias like "linux" or the path of a style file, is added, because setSelectedItem() would
     * ignore it, and the next task would silently run with the default style.
     */
    private static void selectStyle(JComboBox comboBox, String style) {
        javax.swing.DefaultComboBoxModel model = (javax.swing.DefaultComboBoxModel) comboBox.getModel();
        if (model.getIndexOf(style) < 0) {
            int custom = model.getIndexOf("custom");
            model.insertElementAt(style, custom < 0 ? model.getSize() : custom);
        }
        comboBox.setSelectedItem(style);
    }

    // for both the verify panel (verification mode) and the output style panel (calculation mode)
    private void parameters2customStylePanel(
            JCheckBox hashValueEncodingCheckBox, JComboBox hashValueEncodingComboBox,
            JCheckBox includeFileSizeCheckBox, JComboBox outputStyleComboBox,
            JCheckBox includeTimestampCheckBox, JComboBox timestampFormatComboBox, JTextField timestampFormatTextField, JCheckBox lineFormatCheckBox, JTextField lineFormatTextField) {
        
        // Style
        if (parameters.getCompatibilityID() != null) {
            selectStyle(outputStyleComboBox, parameters.getCompatibilityID());
        } else {

            // hash value encoding
            if (parameters.getEncoding() != null) {
                hashValueEncodingCheckBox.setSelected(true);
                hashValueEncodingComboBox.setSelectedItem(Encoding.encoding2String(parameters.getEncoding()));
            }

            // include file size
            if (parameters.isFilesizeWantedSet()) {
                includeFileSizeCheckBox.setSelected(parameters.isFilesizeWanted());
                // Ticking the box switches the style to custom by its listener, but unticking it
                // doesn't, so a custom style whose only change is "no file size" would come back
                // as the default style. The next task would then no longer switch the file size
                // off, and Jacksum prints it by default if several algorithms are combined.
                if (!parameters.isFilesizeWanted()) {
                    outputStyleComboBox.setSelectedItem("custom");
                }
            }

            // include timestamp
            if (parameters.isTimestampWanted()) {
                includeTimestampCheckBox.setSelected(true);
                String timestampCode = parameters.getTimestampFormat();
                String comboItem = timestampKeyword2comboItem(timestampCode);
                if (comboItem != null) {
                    timestampFormatComboBox.setSelectedItem(comboItem);
                } else {
                    timestampFormatComboBox.setSelectedItem("custom");
                    timestampFormatTextField.setText(timestampCode);
                }
            }
            timestampFormatTextField.setEnabled(timestampFormatComboBox.getSelectedItem().equals("custom"));

            // line-format (not available in verify mode)
            if (lineFormatCheckBox != null && parameters.getFormat() != null) {
                lineFormatCheckBox.setSelected(true);
                lineFormatTextField.setText(parameters.getFormat());
            }
        }
    }
    
    
    private void customStylePanel2parameters(
            JCheckBox hashValueEncodingCheckBox, JComboBox hashValueEncodingComboBox,
            JCheckBox includeFileSizeCheckBox, JComboBox outputStyleComboBox,
            JCheckBox includeTimestampCheckBox, JComboBox timestampFormatComboBox, JTextField timestampFormatTextField, JCheckBox lineFormatCheckBox, JTextField lineFormatTextField
            
    ) throws UserInputError {
        
        if (outputStyleComboBox.getSelectedItem().equals("custom")) {

            // line-format (not available in verify mode)
            if (lineFormatCheckBox != null) {
                if (lineFormatCheckBox.isSelected()) {
                    if (lineFormatTextField.getText().equals("")) {
                        parameters.setFormat(null);
                    } else {
                        parameters.setFormat(lineFormatTextField.getText());
                    }
                } else {
                    parameters.setFormat(null);
                }
            }

            // Hash value encoding               
            if (hashValueEncodingCheckBox.isSelected()) {
                parameters.setEncoding(Encoding.string2Encoding(hashValueEncodingComboBox.getSelectedItem().toString()));
            } else {
                parameters.setEncoding((Encoding) null);
            }

            // include file size in bytes
            parameters.unsetFilesizeWanted();
            if (includeFileSizeCheckBox.isSelected() && outputStyleComboBox.getSelectedItem().equals("custom")) {
                parameters.setFilesizeWanted(true);
            }
            if (!includeFileSizeCheckBox.isSelected() && outputStyleComboBox.getSelectedItem().equals("custom")) {
                parameters.setFilesizeWanted(false);
            }

            // include timestamp
            if (includeTimestampCheckBox.isSelected()) {
                if (timestampFormatComboBox.getSelectedItem().equals("custom")) {
                    if (!timestampFormatTextField.getText().isBlank()) {
                        parameters.setTimestampFormat(timestampFormatTextField.getText());
                    } else {
                        // the field is on the calculation or on the verification tab
                        selectTabOf(timestampFormatTextField);
                        JOptionPane.showMessageDialog(this, "The timestamp format has been set to custom, but no format has been entered.");
                        // the example is a placeholder only (see installPlaceholders()), so pressing
                        // the button again doesn't pass it to Jacksum as a format
                        timestampFormatTextField.setText("");
                        timestampFormatTextField.requestFocus();
                        throw new UserInputError();
                    }
                } else {
                    parameters.setTimestampFormat(timestampFormatComboBox.getSelectedItem().toString());
                }
            } else {
                parameters.setTimestampFormat(null);
            }

        }
        
        
        if (outputStyleComboBox.getSelectedItem().equals("default")) {
            parameters.setFormat(null);
            parameters.setEncoding((Encoding) null);
            parameters.unsetFilesizeWanted();
            parameters.setTimestampFormat(null);            
        }
        

        // Style
        if (outputStyleComboBox.getSelectedItem().equals("default") || outputStyleComboBox.getSelectedItem().equals("custom")) {
            parameters.setCompatibilityID(null);
        } else {
            parameters.setCompatibilityID(outputStyleComboBox.getSelectedItem().toString());
        }        
    }

    
    
